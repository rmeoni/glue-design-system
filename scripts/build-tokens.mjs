#!/usr/bin/env node
/**
 * Glue Design System — token build.
 *
 * Reads the DTCG files in /tokens and writes:
 *   css/tokens.css     CSS custom properties (light, dark, auto dark)
 *   dist/tokens.json   flat, resolved values per theme (for tools that do not read references)
 *   dist/glue.css      tokens + base + layout + components in one file
 *
 * No dependencies: `node scripts/build-tokens.mjs` or `npm run build`.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));

const primitives = read("tokens/primitives.tokens.json");
const typography = read("tokens/typography.tokens.json");
const light = read("tokens/semantic.light.tokens.json");
const dark = read("tokens/semantic.dark.tokens.json");

/** Flatten a DTCG tree to [{ path, type, value, description }], inheriting $type. */
function flatten(node, path = [], inheritedType) {
  const out = [];
  const type = node.$type ?? inheritedType;
  if ("$value" in node) {
    out.push({ path, type, value: node.$value, description: node.$description });
    return out;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$") || typeof child !== "object") continue;
    out.push(...flatten(child, [...path, key], type));
  }
  return out;
}

const cssName = (path) => `--${path.join("-")}`;
const refPath = (ref) => ref.slice(1, -1).split(".");
const isRef = (v) => typeof v === "string" && /^\{[^}]+\}$/.test(v);

const index = new Map();
for (const t of [...flatten(primitives), ...flatten(typography)]) index.set(t.path.join("."), t);

function resolve(value, themeIndex) {
  if (isRef(value)) {
    const key = refPath(value).join(".");
    const target = themeIndex.get(key) ?? index.get(key);
    if (!target) throw new Error(`Unresolved reference ${value}`);
    return resolve(target.value, themeIndex);
  }
  if (value && typeof value === "object" && !Array.isArray(value)) {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, themeIndex)]));
  }
  return value;
}

/** CSS text for a token. References stay as var() so themes cascade. */
function toCss(type, value) {
  if (isRef(value)) return `var(${cssName(refPath(value))})`;
  switch (type) {
    case "fontFamily":
      return (Array.isArray(value) ? value : [value])
        .map((f) => (/\s/.test(f) && !f.includes("-") ? `"${f}"` : f))
        .join(", ");
    case "cubicBezier":
      return `cubic-bezier(${value.join(", ")})`;
    case "shadow": {
      const s = value;
      return `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`;
    }
    case "typography": {
      const v = Object.fromEntries(Object.entries(value).map(([k, x]) => [k, toCss(null, x)]));
      return `${v.fontWeight} ${v.fontSize}/${v.lineHeight} ${v.fontFamily}`;
    }
    default:
      return String(value);
  }
}

function block(selector, tokens, indent = "  ") {
  const lines = tokens.map((t) => `${indent}${cssName(t.path)}: ${toCss(t.type, t.value)};`);
  const pad = indent.slice(2);
  return `${pad}${selector} {\n${lines.join("\n")}\n${pad}}`;
}

const prim = flatten(primitives);
const typo = flatten(typography);
const lightTokens = flatten(light);
const darkTokens = flatten(dark);

// Typography tokens also get a letter-spacing variable, since `font` cannot carry it.
const typoExtras = typo.map((t) => ({
  path: [...t.path, "letter-spacing"],
  type: "dimension",
  value: t.value.letterSpacing,
}));

const header = `/* Glue Design System — tokens.css
   GENERATED by scripts/build-tokens.mjs from /tokens. Do not edit by hand. */`;

const css = [
  header,
  block(":root", [...prim, ...typo, ...typoExtras]),
  `/* Light theme (default) */\n${block(':root,\n[data-theme="light"]', lightTokens)}`,
  `/* Dark theme, set explicitly */\n${block('[data-theme="dark"]', darkTokens)}`,
  `/* Dark theme, following the OS when no theme is set */\n@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', darkTokens, "    ")}\n}`,
].join("\n\n") + "\n";

mkdirSync(join(root, "css"), { recursive: true });
mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "css/tokens.css"), css);

// Flat resolved JSON
const themeIndex = (tokens) => new Map(tokens.map((t) => [t.path.join("."), t]));
const flat = (tokens, idx) =>
  Object.fromEntries(tokens.map((t) => [t.path.join("."), resolve(t.value, idx)]));
const lightIdx = themeIndex(lightTokens);
const darkIdx = themeIndex(darkTokens);
writeFileSync(
  join(root, "dist/tokens.json"),
  JSON.stringify(
    {
      primitives: flat([...prim, ...typo], new Map()),
      light: flat(lightTokens, lightIdx),
      dark: flat(darkTokens, darkIdx),
    },
    null,
    2
  ) + "\n"
);

// Icon sprite from assets/icons/*.svg (each file stays the source of truth)
import { readdirSync } from "node:fs";
const iconDir = join(root, "assets/icons");
const symbols = readdirSync(iconDir)
  .filter((f) => f.endsWith(".svg") && f !== "sprite.svg")
  .sort()
  .map((f) => {
    const src = readFileSync(join(iconDir, f), "utf8");
    const viewBox = src.match(/viewBox="([^"]+)"/)[1];
    const sw = src.match(/stroke-width="([^"]+)"/)[1];
    const title = (src.match(/<title>([^<]*)<\/title>/) || [])[1] || "";
    const inner = src.replace(/^[\s\S]*?<\/title>\s*/, "").replace(/\s*<\/svg>\s*$/, "");
    return `  <symbol id="glue-${f.replace(".svg", "")}" viewBox="${viewBox}" fill="none" stroke="currentColor" stroke-width="${sw}" stroke-linejoin="round"><title>${title}</title>${inner.replace(/\n\s*/g, "")}</symbol>`;
  });
writeFileSync(
  join(iconDir, "sprite.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n<!-- GENERATED by scripts/build-tokens.mjs from assets/icons/*.svg -->\n${symbols.join("\n")}\n</svg>\n`
);

// Bundle
const parts = ["css/tokens.css", "css/base.css", "css/layout.css", "css/components.css"];
const bundle = parts
  .map((p) => `/* ---- ${p} ---- */\n${readFileSync(join(root, p), "utf8")}`)
  .join("\n");
writeFileSync(join(root, "dist/glue.css"), bundle);

console.log(
  `Glue tokens: ${prim.length} primitives, ${typo.length} text styles, ${lightTokens.length} semantic (x2 themes).`
);
