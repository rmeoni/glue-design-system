#!/usr/bin/env node
/**
 * Glue Design System — zeroheight export.
 *
 * Writes ONE file for zeroheight's token manager (JSON import, one token set):
 *
 *   dist/zeroheight/glue.tokens.json
 *     color.*, font.*, space.*, radius.*, …   primitives (shared by both themes)
 *     typography.*                            text styles (shared)
 *     light.color.*, light.elevation.*        light theme semantic tokens
 *     dark.color.*,  dark.elevation.*         dark theme semantic tokens
 *
 * Both themes live in the same set because zeroheight plans with a single token set
 * cannot hold a second one. Semantic tokens keep their aliases to the primitives, so
 * `light.color.bg.inverse` shows as {color.navy.700} and `dark.color.bg.inverse` as
 * {color.navy.200}.
 *
 * Value format = what zeroheight's importer validates (not the newer DTCG 2025.10
 * objects, which it rejects): colors as hex strings, dimensions as "16px" / "1rem",
 * durations as "200ms". That is the format of /tokens already, so values are copied
 * as they are; this script only merges, namespaces and validates.
 *
 * Runs as part of `npm run build`. Throws if any value or alias does not validate.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const isRef = (v) => typeof v === "string" && /^\{[^}]+\}$/.test(v);

/** Deep-merge DTCG trees. Throws if two sources define the same token. */
function merge(target, src, path = []) {
  for (const [k, v] of Object.entries(src)) {
    if (k === "$description" && path.length === 0) continue; // file-level notes
    if (v && typeof v === "object" && !Array.isArray(v) && !("$value" in v) && !k.startsWith("$")) {
      target[k] = target[k] || {};
      merge(target[k], v, [...path, k]);
    } else {
      if (k in target && !k.startsWith("$")) throw new Error(`Duplicate token ${[...path, k].join(".")}`);
      if (k === "$type" && target.$type && target.$type !== v)
        throw new Error(`Conflicting $type at ${path.join(".")}: ${target.$type} vs ${v}`);
      target[k] = v;
    }
  }
  return target;
}

/** Visit every token: fn(token, path, inheritedType). */
function eachToken(node, fn, path = [], type) {
  const t = node.$type ?? type;
  if ("$value" in node) return fn(node, path, t);
  for (const [k, c] of Object.entries(node)) {
    if (!k.startsWith("$") && c && typeof c === "object") eachToken(c, fn, [...path, k], t);
  }
}

function lookup(tree, ref) {
  let node = tree, type;
  for (const k of ref.slice(1, -1).split(".")) {
    if (!node || typeof node !== "object") return null;
    type = node.$type ?? type;
    node = node[k];
  }
  return node && "$value" in node ? { node, type: node.$type ?? type } : null;
}

// ---------- assemble ----------
const theme = (file, name) => {
  const t = read(file);
  delete t.$description;
  return { $description: `${name} theme semantic tokens. Components use only these.`, ...t };
};

const out = {
  $description:
    "Glue Design System — all tokens in one set for zeroheight. Primitives and typography are shared; " +
    "semantic tokens are under light.* and dark.*. Generated by scripts/build-zeroheight.mjs from /tokens. Do not edit by hand.",
};
merge(out, read("tokens/primitives.tokens.json"));
merge(out, read("tokens/typography.tokens.json"));
out.light = theme("tokens/semantic.light.tokens.json", "Light");
out.dark = theme("tokens/semantic.dark.tokens.json", "Dark");

// Semantic aliases that point at other semantic tokens (e.g. elevation → shadow is fine,
// but a semantic → semantic alias) must follow the theme prefix.
for (const mode of ["light", "dark"]) {
  eachToken(out[mode], (tok) => {
    const fix = (v) => {
      if (!isRef(v)) return v;
      const key = v.slice(1, -1);
      return lookup(out, v) ? v : lookup(out, `{${mode}.${key}}`) ? `{${mode}.${key}}` : v;
    };
    tok.$value = typeof tok.$value === "object" && tok.$value && !Array.isArray(tok.$value)
      ? Object.fromEntries(Object.entries(tok.$value).map(([k, x]) => [k, fix(x)]))
      : fix(tok.$value);
  });
}

// ---------- validate against zeroheight's import rules ----------
const errors = [];
const DIM = /^-?\d*\.?\d+(px|rem)$/;
const rules = {
  color: (v) => /^#([0-9a-f]{6}|[0-9a-f]{8})$/i.test(v),
  dimension: (v) => DIM.test(v),
  duration: (v) => /^\d*\.?\d+(ms|s)$/.test(v),
  fontFamily: (v) => typeof v === "string" || (Array.isArray(v) && v.every((s) => typeof s === "string")),
  fontWeight: (v) => (typeof v === "number" && v >= 1 && v <= 1000) || typeof v === "string",
  cubicBezier: (v) => Array.isArray(v) && v.length === 4 && v.every((n) => typeof n === "number"),
  number: (v) => typeof v === "number",
};
function check(v, type, where) {
  if (isRef(v)) {
    const hit = lookup(out, v);
    if (!hit) errors.push(`${where}: unresolved alias ${v}`);
    else if (type && hit.type !== type) errors.push(`${where}: alias ${v} is ${hit.type}, expected ${type}`);
    return;
  }
  if (type === "shadow") {
    for (const s of Array.isArray(v) ? v : [v]) {
      check(s.color, "color", `${where}.color`);
      for (const k of ["offsetX", "offsetY", "blur", "spread"]) check(s[k], "dimension", `${where}.${k}`);
    }
    return;
  }
  if (type === "typography") {
    check(v.fontFamily, "fontFamily", `${where}.fontFamily`);
    check(v.fontSize, "dimension", `${where}.fontSize`);
    check(v.fontWeight, "fontWeight", `${where}.fontWeight`);
    check(v.lineHeight, "dimension", `${where}.lineHeight`);
    check(v.letterSpacing, "dimension", `${where}.letterSpacing`);
    return;
  }
  if (!rules[type]) return errors.push(`${where}: unsupported $type ${type}`);
  if (!rules[type](v)) errors.push(`${where}: invalid ${type} ${JSON.stringify(v)}`);
}
let count = 0;
eachToken(out, (tok, path, type) => {
  count++;
  if (!type) return errors.push(`${path.join(".")}: no $type`);
  if (path.some((k) => /[{}.]/.test(k) || k.startsWith("$"))) errors.push(`${path.join(".")}: invalid name`);
  check(tok.$value, type, path.join("."));
});
if (errors.length) throw new Error(`zeroheight export failed validation:\n  ${errors.join("\n  ")}`);

// ---------- write ----------
const dir = join(root, "dist/zeroheight");
rmSync(dir, { recursive: true, force: true }); // drop files from older export layouts
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "glue.tokens.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`zeroheight: dist/zeroheight/glue.tokens.json (${count} tokens: shared + light.* + dark.*).`);
